const dicts = { en, ru, zh } as Record<string, Record<Key, Str>>;

export const LANGS: ["en" | "ru" | "zh", string][] = [
  ["en", "English"],
  ["ru", "Русский"],
  ["zh", "简体中文"],
];

function detect(): string {
  for (const l of navigator.languages || [navigator.language]) {
    const base = l.toLowerCase().split("-")[0];
    if (base in dicts) return base;
  }
  return "en";
}

export const lang = computed(() => (settings.value.lang === "auto" ? detect() : settings.value.lang));

export function t(key: Key, ...args: (string | number)[]): string {
  const code = lang.value;
  let s: Str = dicts[code][key] ?? en[key];
  if (typeof s !== "string") {
    const n = typeof args[0] === "number" ? args[0] : 0;
    const cat = new Intl.PluralRules(code === "zh" ? "zh-CN" : code).select(n);
    s = s[cat] ?? s.other;
  }
  return s.replace(/\{(\d)\}/g, (_, i) => String(args[+i] ?? ""));
}

export const mod = /Mac|iPhone|iPad/.test(navigator.platform || navigator.userAgent) ? "⌘" : "Ctrl";

const locale = () => (lang.value === "zh" ? "zh-CN" : lang.value);

export function fmtDate(iso: string): string {
  return new Date(iso).toLocaleString(locale(), { dateStyle: "medium", timeStyle: "short" });
}

export function fmtAgo(ms: number): string {
  const sec = Math.round((ms - Date.now()) / 1000);
  const rtf = new Intl.RelativeTimeFormat(locale(), { numeric: "auto" });
  if (Math.abs(sec) < 45) return rtf.format(0, "second");
  if (Math.abs(sec) < 3600) return rtf.format(Math.round(sec / 60), "minute");
  if (Math.abs(sec) < 86400) return rtf.format(Math.round(sec / 3600), "hour");
  return rtf.format(Math.round(sec / 86400), "day");
}

