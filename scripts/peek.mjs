// Dev helper: screenshots of the running dev server in demo mode.
//   node scripts/peek.mjs <outdir> [lang] [theme] [width]
import puppeteer from "puppeteer";
const [out = ".", lang = "en", theme = "light", width = "1360"] = process.argv.slice(2);
const browser = await puppeteer.launch({ args: ["--no-proxy-server", `--lang=${lang}`] });
const page = await browser.newPage();
await page.setViewport({ width: +width, height: 820 });
await page.emulateMediaFeatures([{ name: "prefers-color-scheme", value: theme }]);
page.on("console", (m) => m.type() === "error" && console.log("console:", m.text()));
page.on("pageerror", (e) => console.log("pageerror:", e.message));
await page.evaluateOnNewDocument((l) => localStorage.setItem("notewing.settings", JSON.stringify({ lang: l })), lang);
await page.goto("http://localhost:5178/", { waitUntil: "networkidle0" });
await page.screenshot({ path: `${out}/1-setup.png` });
await page.click(".setup-intro .btn");
await page.waitForSelector(".sidebar");
await new Promise((r) => setTimeout(r, 800));
await page.screenshot({ path: `${out}/2-root.png` });
const firstFolder = await page.$(".subfolder");
await firstFolder.click();
await new Promise((r) => setTimeout(r, 500));
await page.screenshot({ path: `${out}/3-folder.png` });
await page.click(".card-link");
await page.waitForSelector(".cm-content");
await new Promise((r) => setTimeout(r, 500));
await page.screenshot({ path: `${out}/4-note.png` });
await page.click('.segmented button:nth-child(2)');
await new Promise((r) => setTimeout(r, 500));
await page.screenshot({ path: `${out}/5-split.png` });
await page.keyboard.down("Control"); await page.keyboard.press("k"); await page.keyboard.up("Control");
await page.keyboard.type(lang === "ru" ? "мука" : "flour");
await new Promise((r) => setTimeout(r, 500));
await page.screenshot({ path: `${out}/6-search.png` });
await page.keyboard.press("Escape");
await page.goto("http://localhost:5178/#/settings");
await new Promise((r) => setTimeout(r, 500));
await page.screenshot({ path: `${out}/7-settings.png` });
await browser.close();
